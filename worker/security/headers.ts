import type { MiddlewareHandler } from "hono";
import type { AppEnv } from "../env";

const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "[::1]"]);

/**
 * Encrypted connections only: any plain-http request is redirected to https
 * (308 keeps the method and body). Local development is left alone.
 */
export const requireHttps: MiddlewareHandler<AppEnv> = async (c, next) => {
  const url = new URL(c.req.url);
  if (url.protocol === "http:" && !LOCAL_HOSTS.has(url.hostname)) {
    url.protocol = "https:";
    return c.redirect(url.toString(), c.req.method === "GET" || c.req.method === "HEAD" ? 301 : 308);
  }
  return next();
};

/**
 * Security headers for responses generated by the Worker (API + public HTML).
 * Static assets get the same policy from public/_headers.
 */
export const securityHeaders: MiddlewareHandler<AppEnv> = async (c, next) => {
  await next();
  // WebSocket upgrade responses (101) have immutable headers; nothing to add there.
  if (c.res.status === 101) return;
  // Asset responses can have immutable headers; copy them into a fresh response.
  try {
    c.res.headers.set("X-Content-Type-Options", "nosniff");
  } catch {
    c.res = new Response(c.res.body, c.res);
  }
  const h = c.res.headers;
  h.set("X-Content-Type-Options", "nosniff");
  h.set("Referrer-Policy", "strict-origin-when-cross-origin");
  h.set("X-Frame-Options", "DENY");
  h.set("X-Robots-Tag", "noindex, nofollow");
  h.set("Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=()");
  if (new URL(c.req.url).protocol === "https:") {
    // Browsers remember to use https for two years, even if someone types http://.
    h.set("Strict-Transport-Security", "max-age=63072000; includeSubDomains");
  }
  if (c.req.path.startsWith("/api/") && !h.has("Cache-Control")) {
    h.set("Cache-Control", "no-store");
  }
};

/**
 * CSRF defence for cookie-authenticated API calls: state-changing requests must
 * come from our own origin. (SameSite=Lax cookies are the first line of defence.)
 */
export const sameOriginGuard: MiddlewareHandler<AppEnv> = async (c, next) => {
  const method = c.req.method.toUpperCase();
  if (method === "GET" || method === "HEAD" || method === "OPTIONS") return next();
  const origin = c.req.header("origin");
  const expected = new URL(c.env.PUBLIC_APP_URL).origin;
  const requestOrigin = new URL(c.req.url).origin;
  if (origin && (origin === expected || origin === requestOrigin)) return next();
  if (!origin) {
    const site = c.req.header("sec-fetch-site");
    if (site === "same-origin") return next();
  }
  return c.json({ error: { code: "bad_origin", message: "Cross-site request rejected" } }, 403);
};
