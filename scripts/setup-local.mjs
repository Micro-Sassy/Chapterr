// Create a .dev.vars file for local development with safe, non-production values.
// Usage: npm run setup:local   (will not overwrite an existing .dev.vars)
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

if (existsSync(".dev.vars") && !process.argv.includes("--force")) {
  console.log(".dev.vars already exists — leaving it alone (use --force to overwrite).");
  process.exit(0);
}

const port = process.env.PORT ?? "5173";
const vars = {
  APP_ENV: "development",
  PUBLIC_APP_URL: `http://localhost:${port}`,
  BETTER_AUTH_SECRET: randomBytes(32).toString("base64url"),
  // "console" prints emails to the terminal and stores them in the dev outbox
  // (GET /api/dev/outbox?to=you@example.com). Switch to "resend" to send real mail.
  EMAIL_PROVIDER: "console",
  EMAIL_FROM: "Teel Ridge Book Club <dev@localhost>",
  RESEND_API_KEY: "",
  // Cloudflare's official Turnstile testing keys: always pass, never use in production.
  TURNSTILE_SITE_KEY: "1x00000000000000000000AA",
  TURNSTILE_SECRET_KEY: "1x0000000000000000000000000000000AA",
  GOOGLE_BOOKS_API_KEY: "",
};
writeFileSync(
  ".dev.vars",
  `# Local development values generated by scripts/setup-local.mjs. Git-ignored.\n${Object.entries(vars)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n")}\n`,
);
console.log("Wrote .dev.vars for local development.");
